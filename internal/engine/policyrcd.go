package engine

import (
	"bytes"
	"errors"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/iamletenkov/cream/internal/cerr"
)

// policyRcDBody is cream's /usr/sbin/policy-rc.d: exit 101 forbids
// invoke-rc.d to start services while a build hook runs (§12.2).
const policyRcDBody = "#!/bin/sh\n# Generated by cream for the build phase: services are not started.\nexit 101\n"

// policyRcDPut puts cream's policy-rc.d when the guest has none and
// returns the function that removes it; an existing one (the image's own)
// stays untouched and the returned function does nothing.
func (e *Engine) policyRcDPut() (func(), error) {
	p := e.L.PolicyRcD()
	_, err := os.Lstat(p)
	switch {
	case err == nil:
		return func() {}, nil
	case !errors.Is(err, fs.ErrNotExist):
		return nil, cerr.Wrap(err, cerr.ExitState, cerr.CodeIORead, "policy-rc.d %s", p)
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return nil, cerr.Wrap(err, cerr.ExitState, cerr.CodeIOWrite, "policy-rc.d %s", p)
	}
	f, err := os.OpenFile(p, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o755)
	if err != nil {
		return nil, cerr.Wrap(err, cerr.ExitState, cerr.CodeIOWrite, "policy-rc.d %s", p)
	}
	_, werr := f.WriteString(policyRcDBody)
	if cl := f.Close(); werr == nil {
		werr = cl
	}
	if werr == nil {
		werr = os.Chmod(p, 0o755) // umask could have narrowed the mode
	}
	if werr != nil {
		_ = os.Remove(p)
		return nil, cerr.Wrap(werr, cerr.ExitState, cerr.CodeIOWrite, "policy-rc.d %s", p)
	}
	return func() { e.policyRcDDrop(p) }, nil
}

// policyRcDDrop removes cream's policy-rc.d; a file a hook replaced it with
// stays, with a warning.
func (e *Engine) policyRcDDrop(p string) {
	st, err := os.Lstat(p)
	if errors.Is(err, fs.ErrNotExist) {
		return
	}
	var data []byte
	if err == nil && st.Mode().IsRegular() {
		data, err = os.ReadFile(p)
	}
	if err == nil && !bytes.Equal(data, []byte(policyRcDBody)) {
		e.warn("build.policy_rc_d", "%s заменён хуком — оставлен как есть", p)
		return
	}
	if err == nil {
		err = os.Remove(p)
	}
	if err != nil {
		e.warn("build.policy_rc_d", "%s не удалён: %v", p, err)
	}
}
