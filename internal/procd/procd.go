// Package procd places the configure of cream on OpenWrt (spec OpenWrt
// §4.1, ADR-0005): two rc.common init scripts run the configure hooks of the
// enabled extensions at boot, stage by stage, and the enabled instances are
// empty files in /opt/cream/var/stages/<stage>/<ext> — the analogue of the
// .wants links of systemd. All of it works on files under paths.Layout.Root,
// without a running procd, so the build phase enables instances the same way
// a live machine does.
//
// The scripts are plain rc.common, not USE_PROCD services: procd runs the
// rc.d boot scripts one by one and waits for each (rcS, max_running_tasks 1,
// no timeout on boot), so the early stage is done before S20network, while a
// procd instance would only be queued. Within a stage the instances run in
// the order of their names.
package procd

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/iamletenkov/cream/internal/cerr"
	"github.com/iamletenkov/cream/internal/fsx"
	"github.com/iamletenkov/cream/internal/paths"
)

// CodeStageUnsupported is a stage procd does not have (graphical) or an
// unknown one; the code is the one systemd uses for an unknown stage.
const CodeStageUnsupported = "stage.unsupported"

// CodeOrderUnsupported is after/before/wants of a configure on OpenWrt: the
// order there is the stage only.
const CodeOrderUnsupported = "stage.order_unsupported"

// script is one init script: its name in /etc/init.d, START and the stages
// it runs, in order.
type script struct {
	name   string
	start  int
	stages []string
}

// scripts are the init scripts of cream: early before the network (S20),
// system and cloud-user after it and after wrt.cloudinit (S47).
var scripts = []script{
	{name: "cream-configure-early", start: 19, stages: []string{"early"}},
	{name: "cream-configure", start: 95, stages: []string{"system", "cloud-user"}},
}

// Script is the name of the init script that runs the system stage, as
// `cream system init` reports it.
const Script = "cream-configure"

// Stages are the configure stages of OpenWrt, in boot order.
func Stages() []string {
	var out []string
	for _, s := range scripts {
		out = append(out, s.stages...)
	}
	return out
}

// link is the rc.d start link, S<NN><name>, as `/etc/init.d/<name> enable` makes it.
func (s script) link() string { return fmt.Sprintf("S%02d%s", s.start, s.name) }

// The paths the script reads on the machine itself, never under --root.
const (
	guestStages    = "/opt/cream/var/stages/"
	guestInstalled = "/opt/cream/var/installed/"
	guestBin       = "/usr/bin/cream"
)

// guestTmp is TMPDIR of hooks on the machine: on disk, so nothing clears it
// at boot but the first script.
const guestTmp = "/opt/cream/var/tmp"

// clean is the start of the first boot script: TMPDIR of hooks is emptied
// as /tmp would be by a reboot.
func (s script) clean() string {
	if s.start != scripts[0].start {
		return ""
	}
	return "\t# TMPDIR of hooks is on disk: empty it at boot, as a reboot empties /tmp.\n" +
		"\trm -rf " + guestTmp + "/* " + guestTmp + "/.[!.]* " + guestTmp + "/..?* 2>/dev/null || :\n"
}

// body renders the init script.
func (s script) body() []byte {
	var b strings.Builder
	fmt.Fprintf(&b, `#!/bin/sh /etc/rc.common
# Generated by cream (cream system init): configure of installed extensions
# at boot, stages: %[1]s. Do not edit — cream rewrites this file.
# The output goes to the system log: logread -e cream-configure

START=%[2]d
stages="%[1]s"

start() {
	[ -x %[3]s ] || return 0
%[6]s	for stage in $stages; do
		for mark in %[4]s"$stage"/*; do
			[ -f "$mark" ] || continue
			ext="${mark##*/}"
			[ -f "%[5]s$ext.json" ] || continue
			%[3]s configure --from-unit "$ext" </dev/null || :
		done
	done
}
`, strings.Join(s.stages, " "), s.start, guestBin, guestStages, guestInstalled, s.clean())
	return []byte(b.String())
}

func scriptOf(stage string) (script, error) {
	for _, s := range scripts {
		if slices.Contains(s.stages, stage) {
			return s, nil
		}
	}
	e := cerr.New(cerr.ExitData, CodeStageUnsupported,
		"стадия configure %q на OpenWrt не поддерживается (early, system, cloud-user)", stage)
	e.Details = map[string]any{"stage": stage, "family": paths.FamilyOpenWrt}
	return script{}, e
}

// Target is the rc.d link that runs stage: what the registry records as
// configure.target.
func Target(stage string) (string, error) {
	s, err := scriptOf(stage)
	if err != nil {
		return "", err
	}
	return s.link(), nil
}

// Init prepares the machine (`cream system init` on OpenWrt): the cream
// directories with their modes, the stage lists, both init scripts and their
// rc.d links. Repeating it is a no-op; a script that differs is rewritten.
func Init(l paths.Layout) error {
	dirs := l.InitDirs()
	for _, st := range Stages() {
		dirs = append(dirs, paths.Dir{Path: l.StageDir(st), Mode: 0o755})
	}
	for _, d := range dirs {
		if err := os.MkdirAll(d.Path, 0o755); err != nil {
			return fmt.Errorf("system init: %w", err)
		}
		if err := os.Chmod(d.Path, d.Mode); err != nil {
			return fmt.Errorf("system init: %w", err)
		}
	}
	for _, s := range scripts {
		if err := place(l, s); err != nil {
			return fmt.Errorf("system init: %w", err)
		}
	}
	return nil
}

// place writes the init script s when it differs and links it into rc.d.
func place(l paths.Layout, s script) error {
	p := l.InitScript(s.name)
	body := s.body()
	cur, err := os.ReadFile(p)
	st, serr := os.Lstat(p)
	if err != nil || !bytes.Equal(cur, body) || serr != nil || !st.Mode().IsRegular() || st.Mode().Perm() != 0o755 {
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := fsx.WriteAtomic(p, body, 0o755); err != nil {
			return err
		}
	}
	return symlink(l.RcLink(s.link()), "../init.d/"+s.name)
}

// symlink makes p a link to dst atomically; an equal link is left alone.
func symlink(p, dst string) error {
	if cur, err := os.Readlink(p); err == nil && cur == dst {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	tmp := p + ".cream-tmp"
	_ = os.Remove(tmp)
	if err := os.Symlink(dst, tmp); err != nil {
		return err
	}
	if err := os.Rename(tmp, p); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}

// Enable puts the stage mark of ext and returns the target (the rc.d link of
// the stage); a mark at another stage is removed. The init script of the
// stage is placed as well: the build phase may run a cream that never ran
// system init. ordered is a configure with after/before/wants: refused, as is
// a stage OpenWrt does not have (65).
func Enable(l paths.Layout, ext, stage string, ordered bool) (string, error) {
	s, err := scriptOf(stage)
	if err != nil {
		return "", err
	}
	if ordered {
		e := cerr.New(cerr.ExitData, CodeOrderUnsupported,
			"%s: after, before и wants у configure на OpenWrt не поддерживаются — порядок задаёт только стадия", ext)
		e.Details = map[string]any{"ext": ext, "family": paths.FamilyOpenWrt}
		return "", e
	}
	if err := place(l, s); err != nil {
		return "", fmt.Errorf("включение configure %s: %w", ext, err)
	}
	for _, st := range Stages() {
		if st == stage {
			continue
		}
		if err := removeMark(l.StageMark(st, ext)); err != nil {
			return "", fmt.Errorf("включение configure %s: %w", ext, err)
		}
	}
	p := l.StageMark(stage, ext)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return "", fmt.Errorf("включение configure %s: %w", ext, err)
	}
	if err := fsx.WriteAtomic(p, nil, 0o644); err != nil {
		return "", fmt.Errorf("включение configure %s: %w", ext, err)
	}
	return s.link(), nil
}

// Disable removes the stage marks of ext; the init scripts stay (they
// belong to cream, not to the extension).
func Disable(l paths.Layout, ext string) error {
	for _, st := range Stages() {
		if err := removeMark(l.StageMark(st, ext)); err != nil {
			return fmt.Errorf("отключение configure %s: %w", ext, err)
		}
	}
	return nil
}

func removeMark(p string) error {
	if err := os.Remove(p); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}
